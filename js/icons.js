// Fungsi global pembuat elemen SVG icon
function ic(nama, kelas = 'w-5 h-5') {
  return `<svg class="ic ${kelas}" aria-hidden="true" focusable="false"><use href="#i-${nama}"></use></svg>`;
}

// Suntikkan sprite ke awal body segera saat DOM siap
function initIconSprite() {
  if (document.getElementById('svg-icon-sprite')) return;
  const wrapper = document.createElement('div');
  wrapper.id = 'svg-icon-sprite';
  wrapper.innerHTML = SPRITE_SVG;
  if (document.body) {
    const skipLink = document.body.querySelector('.skip-link');
    document.body.insertBefore(wrapper, skipLink ? skipLink.nextSibling : document.body.firstChild);
  } else {
    document.addEventListener('DOMContentLoaded', () => {
      const skipLink = document.body.querySelector('.skip-link');
      document.body.insertBefore(wrapper, skipLink ? skipLink.nextSibling : document.body.firstChild);
    });
  }
}

if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', initIconSprite);
} else {
  initIconSprite();
}
